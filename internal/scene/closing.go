package scene

// Закрытие окна — тоже выход из игры.
//
// Крестик в углу окна ничем не хуже пункта «выход»: игрок им пользуется, и
// потерять на нём полминуты забега (интервал автосохранения) обиднее всего.
// Поэтому движок перехватывает закрытие (ebiten.SetWindowClosingHandled) и даёт
// сцене последний тик — вот он.
//
// Сцен, которым есть что сохранить, ровно одна — забег, но открыт может быть
// экран поверх него (пауза, сумка, сундук). Поэтому каждая такая сцена умеет
// передать просьбу дальше, вглубь, до самого забега.

// Closer — сцена, которой есть что дописать на диск перед выходом.
type Closer interface{ Closing() }

// Closing — забег ложится на диск целиком.
func (g *Game) Closing() { g.persist() }

// Closing — под затемнением паузы или смерти лежит забег.
func (o *overlay) Closing() { closing(o.under) }

// Closing — окно героя открыто поверх забега.
func (v *equipView) Closing() { closing(v.g) }

// Closing — окно сундука открыто поверх забега.
func (v *chestView) Closing() { closing(v.g) }

// Closing — из настроек возвращаются туда, откуда пришли; если это пауза
// забега, сохранить надо и его.
func (s *Settings) Closing() { closing(s.back) }

// closing передаёт просьбу сцене, если та её понимает.
func closing(s Scene) {
	if c, ok := s.(Closer); ok {
		c.Closing()
	}
}

package mob

import (
	"github.com/vladislav/game/internal/engine"
	"github.com/vladislav/game/internal/progress"
)

// XPRange — сколько опыта отдаёт существо: полоса «от и до», а не одно число.
// Разброс нужен затем же, зачем разброс в дропе: две одинаковые твари не должны
// быть одинаковы до последней цифры.
//
// Полоса записана в таблицах, а не выведена из силы, потому что это подарок
// игроку, и он бывает нарочно щедрее силы (золотой слизень, боссы). Опорную
// полосу уровня считает progress.Band, и сверка таблиц следит, чтобы отклонение
// от неё было осмысленным, а не опечаткой.
type XPRange struct {
	Min int `json:"min"`
	Max int `json:"max"`
}

// Pick — сколько опыта отдаст эта особь. Выбор делается один раз, при рождении:
// всплывающее над трупом число и то, что упало в полосу героя, обязаны совпасть.
//
// Не бросок по общему генератору, а выбор по затравке — по той же причине, по
// которой у зверей, врагов, добычи и сундука разные зёрна: награда не должна
// двигать последовательность, на которой стоит поведение. Иначе прибавка опыта
// молча меняет то, куда моб пойдёт, — а это уже другая игра при том же сиде.
func (r XPRange) Pick(seed uint64) int {
	if r.Max <= r.Min {
		return max(r.Min, 0)
	}
	return r.Min + int(mix(seed)%uint64(r.Max-r.Min+1))
}

// XPSeed — затравка выбора для особи вида id, рождённой в точке pos. Место
// рождения уже случайно (его выбрал спавнер по сиду карты), поэтому одна и та
// же карта раздаёт один и тот же опыт, а соседи по стае получают разный.
func XPSeed(id string, pos engine.Vec2) uint64 {
	h := uint64(1469598103934665603)
	for i := range len(id) {
		h = (h ^ uint64(id[i])) * 1099511628211
	}
	h ^= uint64(int64(pos.X*16)) * 0x9E3779B97F4A7C15
	h ^= uint64(int64(pos.Y*16)) * 0xC2B2AE3D27D4EB4F
	return h
}

// mix — финализатор splitmix64: раскидывает близкие затравки (соседние клетки)
// по всей разрядной сетке.
func mix(x uint64) uint64 {
	x += 0x9E3779B97F4A7C15
	x = (x ^ (x >> 30)) * 0xBF58476D1CE4E5B9
	x = (x ^ (x >> 27)) * 0x94D049BB133111EB
	return x ^ (x >> 31)
}

// Mid — середина полосы. По ней спавнер считает опасность: бросок у каждой
// особи свой, а место на карте должен занимать вид, а не удача.
func (r XPRange) Mid() float64 { return float64(r.Min+r.Max) / 2 }

// Level — уровень тира: выводится из его чисел, в таблице не хранится.
func (t *Tier) Level() int { return progress.MobLevel(t.HP, t.Damage) }

// Level — уровень вида: там же и по тому же правилу, что у врагов.
func (s *Species) Level() int { return progress.MobLevel(s.Stats.HP, s.Threat.Damage) }

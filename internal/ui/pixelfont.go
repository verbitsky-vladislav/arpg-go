// glyphCache — по картинке 5×7 на символ (белые пиксели, прозрачный фон);
// цвет накладывается при отрисовке через ColorScale. Заполняется лениво и
// только из горутины отрисовки Ebiten, поэтому без мьютекса.
var glyphCache = map[rune]*ebiten.Image{}

func glyphImage(r rune) *ebiten.Image {
	if img, ok := glyphCache[r]; ok {
		return img
	}
	rows, ok := glyphs[r]
	if !ok {
		rows, ok = glyphs['?']
		if !ok {
			return nil
		}
	}
	px := make([]byte, glyphW*glyphH*4)
	for y := range glyphH {
		for x := 0; x < glyphW && x < len(rows[y]); x++ {
			if rows[y][x] != '#' {
				continue
			}
			i := (y*glyphW + x) * 4
			px[i], px[i+1], px[i+2], px[i+3] = 0xff, 0xff, 0xff, 0xff
		}
	}
	img := ebiten.NewImage(glyphW, glyphH)
	img.WritePixels(px)
	glyphCache[r] = img
	return img
}

// PixelTextWidth — ширина строки s в экранных пикселях при масштабе scale
// (без разрядки после последнего глифа).
func PixelTextWidth(s string, scale float64) float64 {
	n := len([]rune(s))
	if n == 0 {
		return 0
	}
	return float64(n*glyphA-1) * scale
}

// PixelTextHeight — высота строки в экранных пикселях при масштабе scale.
func PixelTextHeight(scale float64) float64 { return glyphH * scale }

// PixelText печатает s пиксельным шрифтом; (x,y) — левый верхний угол,
// scale — сколько экранных пикселей на пиксель шрифта (целое — чёткий арт).
func PixelText(dst *ebiten.Image, s string, x, y, scale float64, col color.Color) {
	for i, r := range []rune(s) {
		img := glyphImage(unicode.ToUpper(r))
		if img == nil {
			continue
		}
		op := &ebiten.DrawImageOptions{}
		op.GeoM.Scale(scale, scale)
		op.GeoM.Translate(x+float64(i*glyphA)*scale, y)
		op.ColorScale.ScaleWithColor(col)
		dst.DrawImage(img, op)
	}
}

// PixelTextRot90 печатает s снизу вверх (повёрнутым на 90° против часовой):
// (x,y) — левый нижний угол блока, строка растёт вверх. Нужен для «закладок»
// книги и прочих вертикальных подписей; поворот на прямой угол пиксели не мылит.
func PixelTextRot90(dst *ebiten.Image, s string, x, y, scale float64, col color.Color) {
	for i, r := range []rune(s) {
		img := glyphImage(unicode.ToUpper(r))
		if img == nil {
			continue
		}
		op := &ebiten.DrawImageOptions{}
		op.GeoM.Scale(scale, scale)
		op.GeoM.Translate(float64(i*glyphA)*scale, 0)
		op.GeoM.Rotate(-math.Pi / 2) // (px,py) → (py,-px): глифы уходят вверх
		op.GeoM.Translate(x, y)
		op.ColorScale.ScaleWithColor(col)
		dst.DrawImage(img, op)
	}
}

// PixelTextFit обрезает s до ширины maxW, помечая обрезку точкой.
func PixelTextFit(s string, maxW, scale float64) string {
	rs := []rune(s)
	if PixelTextWidth(string(rs), scale) <= maxW {
		return s
	}
	for len(rs) > 0 {
		rs = rs[:len(rs)-1]
		if PixelTextWidth(string(rs)+".", scale) <= maxW {
			return string(rs) + "."
		}
	}
	return ""
}

// PixelTextCentered печатает s так, чтобы центр строки был в cx, верх — y.
// Левый край округляется до целого пикселя — иначе глифы «поплывут».
func PixelTextCentered(dst *ebiten.Image, s string, cx, y, scale float64, col color.Color) {
	PixelText(dst, s, float64(int(cx-PixelTextWidth(s, scale)/2)), y, scale, col)
}

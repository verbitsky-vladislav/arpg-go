// Package progress — рост героя: цена уровня, уровень существа и опыт за него.
//
// Здесь лежит вся арифметика прокачки и ничего кроме неё: пакет не знает ни про
// сцену, ни про мобов, ни про экран. Уровень существа выводится из его чисел
// (здоровье и урон), а не хранится в таблицах, — так он не может разойтись с
// балансом при первой же правке hp. Сколько опыта существо отдаёт, наоборот,
// лежит в данных (mobs/*.json, поле xp): это подарок игроку, и он бывает
// нарочно щедрее или скупее, чем следует из силы (золотой слизень, боссы).
//
// Числа отсюда сходятся друг с другом: Band(L) — это Need(L), поделённый на
// kills(L), то есть «столько-то убийств ровесника на уровень». Меняя одно,
// смотрите на второе.
package progress

import "math"

// MaxLevel — потолок героя. Существующего контента на него заведомо не хватает:
// лес — первая локация, и мобы в нём кончаются на десятом уровне (см. OutlevelGap).
const MaxLevel = 100

// Цена уровня. Первый уровень стоит BaseNeed, дальше каждый следующий дороже
// предыдущего в g раз, и сам g падает с StartRatio до TailRatio:
//
//	уровень 1 → 2:  100
//	уровень 2 → 3:  120   (×1.20 — та самая «градация в 1.2»)
//	уровень 3 → 4:  143   (×1.19)
//	уровень 10 → 11: 423  (×1.15)
//	уровень 50 → 51: 14370 (×1.08)
//
// Постоянные 1.2 до сотого уровня дали бы 8.9 миллиарда опыта за последний
// уровень — числа, которых не выдержит ни один моб. Затухание оставляет ранним
// уровням обещанный темп, а поздним — достижимую цену: вся дорога до сотого
// стоит около 3.8 миллиона.
const (
	BaseNeed   = 100
	StartRatio = 1.20
	TailRatio  = 1.05
	ratioTau   = 20.0 // за сколько уровней разрыв между ratio гаснет в e раз
)

// Уровень существа по его числам: power = HP + DamageWeight×урон, и каждые
// LevelStep единиц силы — это уровень. Урон весит больше здоровья, потому что
// бьёт по игроку он каждый удар, а здоровье тратится один раз за жизнь.
//
// LevelFloor — сила самого слабого врага в игре (крыса: 18 + 6×4 = 42), она же
// начало первого уровня. Всё, что слабее (курица, зайчонок), — тоже первый.
const (
	DamageWeight = 6
	LevelFloor   = 40
	LevelStep    = 30
)

// OutlevelGap — на сколько уровней надо перерасти моба, чтобы он перестал
// давать опыт. Разрыв ровно в два уровня и есть граница локации: в лесу самый
// сильный — древень десятого уровня, значит выше двенадцатого лес не прокачает.
const OutlevelGap = 2

// PointsPerLevel — очков прокачки за уровень. Тратить их пока некуда; они
// копятся, чтобы дереву умений было что раздавать, когда оно появится.
const PointsPerLevel = 1

// Разброс опыта вокруг середины полосы: одна и та же тварь отдаёт то чуть
// меньше, то чуть больше. Разброс несимметричный — щедрая сторона шире скупой,
// чтобы «повезло» случалось заметнее, чем «не повезло».
const (
	BandLow  = 0.80
	BandHigh = 1.25
)

// Сколько убийств ровесника стоит уровень:
//
//	уровень   1 →    5
//	уровень  10 →   10
//	уровень  50 →  100
//	уровень 100 → 1000
//
// Здесь и живёт «первые уровни качаются быстрее», и живёт целиком: цена уровня
// в опыте растёт ×2000 за сотню уровней, а цена в убийствах — ×200, и разницу
// отыгрывает это число. Побочное следствие полезное: опыт за моба остаётся
// читаемым от начала до конца игры (десятки на первых уровнях, сотни на
// последних), а не разрастается в шестизначные числа.
//
// Растёт число убийств геометрически с затухающим приростом: логарифм
// прибавляется на KillsSlope0 за уровень в начале и на KillsSlopeTail в конце.
// Затухание обязано быть: прирост убийств должен всё время оставаться ниже
// разгона цены уровня (StartRatio→TailRatio), иначе опыт за моба перестал бы
// расти с его уровнем — и тварь посильнее платила бы меньше слабой.
const (
	KillsMin       = 5.0
	KillsSlope0    = 0.0835
	KillsSlopeTail = 0.045
	killsSlopeTau  = 23.5
)

// need[L] — опыт для перехода с уровня L на L+1. Индекс 0 не используется,
// need[MaxLevel] — ноль: с потолка уходить некуда.
var need = buildNeed()

func buildNeed() [MaxLevel + 1]int {
	var t [MaxLevel + 1]int
	t[1] = BaseNeed
	for l := 2; l < MaxLevel; l++ {
		g := TailRatio + (StartRatio-TailRatio)*math.Exp(-float64(l-2)/ratioTau)
		t[l] = int(math.Round(float64(t[l-1]) * g))
	}
	return t
}

// Need — опыт, который надо набрать на уровне level, чтобы уйти на следующий.
// Ноль означает «дальше некуда»: потолок или бессмысленный аргумент.
func Need(level int) int {
	if level < 1 || level >= MaxLevel {
		return 0
	}
	return need[level]
}

// Total — сколько опыта суммарно нужно с первого уровня, чтобы достичь level.
func Total(level int) int {
	sum := 0
	for l := 1; l < level && l < MaxLevel; l++ {
		sum += need[l]
	}
	return sum
}

// MobLevel — уровень существа по его здоровью и урону.
func MobLevel(hp, damage int) int {
	power := hp + DamageWeight*damage
	l := 1 + (power-LevelFloor)/LevelStep
	return min(max(l, 1), MaxLevel)
}

// Kills — сколько ровесников надо убить, чтобы уйти с уровня level на следующий.
func Kills(level int) float64 {
	x := max(float64(level-1), 0)
	return KillsMin * math.Exp(KillsSlopeTail*x+
		(KillsSlope0-KillsSlopeTail)*killsSlopeTau*(1-math.Exp(-x/killsSlopeTau)))
}

// Band — сколько опыта положено давать существу уровня level. Это опорная
// полоса баланса, а не то, что реально записано в таблицах: боссы и золотой
// слизень намеренно выходят за неё (см. BandOff).
func Band(level int) (lo, hi int) {
	level = min(max(level, 1), MaxLevel)
	mid := float64(Need(min(level, MaxLevel-1))) / Kills(level)
	return int(math.Round(mid * BandLow)), int(math.Round(mid * BandHigh))
}

// BandOff — во сколько раз опыт xp щедрее (>1) или скупее (<1) полосы своего
// уровня. Нужен сверкам таблиц: опечатка в нуле видна сразу, а осмысленный
// подарок вроде золотого слизня объясняется в данных.
func BandOff(level, xp int) float64 {
	lo, hi := Band(level)
	mid := float64(lo+hi) / 2
	if mid <= 0 {
		return 0
	}
	return float64(xp) / mid
}

// Gain — сколько опыта герой уровня playerLevel получит за моба уровня
// mobLevel, которому положено xp. Переросший добычу не получает ничего: разрыв
// в OutlevelGap уровней означает, что драка была не боем, а уборкой.
func Gain(playerLevel, mobLevel, xp int) int {
	if xp <= 0 || playerLevel >= MaxLevel || playerLevel-mobLevel >= OutlevelGap {
		return 0
	}
	return xp
}

// Character — прокачка одного героя: где он и сколько накопил.
//
// XP — остаток на текущем уровне, а не всего за жизнь: полоса на экране
// показывает именно его, и хранить сумму, из которой её каждый раз надо
// вычитать, незачем.
type Character struct {
	Level  int
	XP     int
	Points int
}

// New — герой первого уровня.
func New() Character { return Character{Level: 1} }

// Add начисляет опыт и поднимает уровни, пока хватает набранного. Возвращает,
// сколько уровней взято за этот вызов, — по нему игровой слой решает, шуметь ли.
func (c *Character) Add(xp int) int {
	if c.Level < 1 {
		c.Level = 1
	}
	if xp <= 0 || c.Level >= MaxLevel {
		return 0
	}
	c.XP += xp
	got := 0
	for c.Level < MaxLevel && c.XP >= Need(c.Level) {
		c.XP -= Need(c.Level)
		c.Level++
		c.Points += PointsPerLevel
		got++
	}
	// На потолке копить нечего: полоса замирает полной.
	if c.Level >= MaxLevel {
		c.XP = 0
	}
	return got
}

// Frac — доля набранного до следующего уровня, 0..1. На потолке — 1.
func (c *Character) Frac() float64 {
	n := Need(c.Level)
	if n <= 0 {
		return 1
	}
	return min(float64(c.XP)/float64(n), 1)
}

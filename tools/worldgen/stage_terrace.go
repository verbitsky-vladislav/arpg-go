package main

// stage_terrace.go — выравнивание южной кромки плато в террасы.
//
// Округлая макушка сама по себе хороша, но её нижняя граница спускается по
// диагонали — уровень меняется каждую колонку. Юбка обрыва под такой кромкой
// распадается на одноклеточные ступени, а их стыки требуют угловых комбинаций
// «вырез сверху» (1,0,1,1 / 0,1,1,1) и диагоналей (1,0,1,0 / 0,1,0,1), которых в
// cliff_face нет: художник рисовал обрыв как прямую стену. Раньше на эти ключи
// в манифесте стоял сплошной камень — отсюда и лесенка из кубиков на скосах.
//
// Здесь кромка приводится к террасам шириной terraceWidth: пары соседних колонок
// получают общий уровень низа. Тогда любая ступень имеет площадку минимум в две
// клетки, и все стыки закрываются размеченными комбинациями.

// terraceWidth — минимальная ширина площадки южной кромки в клетках.
const terraceWidth = 2

func (g *Generator) stagePlateauTerrace() {
	W, H := g.P.Width, g.P.Height
	isP := func(x, y int) bool { return g.Level.In(x, y) && g.Level.At(x, y) == Plateau }
	for pass := 0; pass < 8; pass++ {
		// нижняя кромка каждой колонки: самая глубокая клетка плато, под которой
		// плато уже нет. Колонки без плато пропускаем.
		bottom := make([]int, W)
		for x := 0; x < W; x++ {
			bottom[x] = -1
			for y := H - 1; y >= 0; y-- {
				if isP(x, y) && !isP(x, y+1) {
					bottom[x] = y
					break
				}
			}
		}
		cut := 0
		for x0 := 0; x0 < W; x0 += terraceWidth {
			// уровень террасы — самый высокий (наименьший y) в паре: опускать
			// кромку нельзя, плато можно только срезать
			lvl := -1
			for x := x0; x < x0+terraceWidth && x < W; x++ {
				if bottom[x] >= 0 && (lvl < 0 || bottom[x] < lvl) {
					lvl = bottom[x]
				}
			}
			if lvl < 0 {
				continue
			}
			for x := x0; x < x0+terraceWidth && x < W; x++ {
				for y := bottom[x]; y > lvl; y-- {
					if isP(x, y) {
						g.Level.Set(x, y, Ground)
						if g.Kind != nil {
							g.Kind.Set(x, y, uint8(kindNone))
						}
						cut++
					}
				}
			}
		}
		if cut == 0 {
			return
		}
	}
}
